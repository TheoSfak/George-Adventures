"""Generates every sound of the game (no downloads, no external audio libraries).

    python tools/gen_audio.py           # sfx + music
    python tools/gen_audio.py sfx       # only the sound effects  -> assets/audio/sfx/*.wav
    python tools/gen_audio.py music     # only the music loops    -> assets/audio/music/*.wav
    python tools/gen_audio.py sfx footstep sword   # only recipes whose name contains these words

Needs only numpy. Recipes live in tools/audio/sfx.py and tools/audio/music.py; edit them and
re-run. The sfx index the game reads is written to scripts/sfx_ids.gd.
"""
import os
import sys
import time

import numpy as np

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
sys.path.insert(0, os.path.join(HERE, "audio"))

import synth as S  # noqa: E402

SFX_DIR = os.path.join(ROOT, "assets", "audio", "sfx")
MUSIC_DIR = os.path.join(ROOT, "assets", "audio", "music")
SFX_RATE = 32000
LOOP_RATE = 22050


def gen_sfx(filters):
    import sfx
    os.makedirs(SFX_DIR, exist_ok=True)
    variants = {}
    loops = []
    total = 0
    for name, (fn, count, gain, loop) in sfx.REG.items():
        if filters and not any(f in name for f in filters):
            variants[name] = count
            if loop:
                loops.append(name)
            continue
        S.set_rate(LOOP_RATE if loop else SFX_RATE)
        for i in range(count):
            rng = np.random.RandomState((sum(map(ord, name)) * 131 + i * 977) % (2 ** 31))
            x = np.asarray(fn(rng, i), dtype=np.float64)
            assert np.all(np.isfinite(x)), name
            x = x - np.mean(x)
            x = S.normalize(x, gain)
            if not loop:
                x = S.fade(x, 0.002, 0.02)
            path = os.path.join(SFX_DIR, "%s_%d.wav" % (name, i + 1) if count > 1 else "%s.wav" % name)
            S.save_wav(path, x, S.SR)
            total += 1
        variants[name] = count
        if loop:
            loops.append(name)
    write_index(variants, loops)
    print("sfx: %d files written to %s" % (total, SFX_DIR))


def write_index(variants, loops):
    lines = ["class_name SfxIds",
             "## GENERATED by tools/gen_audio.py - do not edit by hand.",
             "## Sound-effect name -> number of variants (files name_1.wav ... name_N.wav, or name.wav for 1).",
             "",
             "const VARIANTS := {"]
    for name in sorted(variants):
        lines.append('\t"%s": %d,' % (name, variants[name]))
    lines.append("}")
    lines.append("")
    lines.append("const LOOPS := [")
    for name in sorted(loops):
        lines.append('\t"%s",' % name)
    lines.append("]")
    with open(os.path.join(ROOT, "scripts", "sfx_ids.gd"), "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(lines) + "\n")


def gen_music(filters):
    import music
    os.makedirs(MUSIC_DIR, exist_ok=True)
    names = []
    for name, fn in music.TRACKS.items():
        names.append(name)
        if filters and not any(f in name for f in filters):
            continue
        t0 = time.time()
        S.set_rate(music.RATE)
        x = np.asarray(fn(), dtype=np.float64)
        assert np.all(np.isfinite(x)), name
        x = x - np.mean(x)
        x = S.normalize(x, 0.8)
        S.save_wav(os.path.join(MUSIC_DIR, name + ".wav"), x, music.RATE)
        print("music %-10s %5.1f s  (%.1f s to render)" % (name, len(x) / music.RATE, time.time() - t0))
    with open(os.path.join(ROOT, "scripts", "music_ids.gd"), "w", encoding="utf-8", newline="\n") as f:
        f.write("class_name MusicIds\n## GENERATED by tools/gen_audio.py - do not edit by hand.\n\nconst ALL := [\n")
        for n in names:
            f.write('\t"%s",\n' % n)
        f.write("]\n")


if __name__ == "__main__":
    args = sys.argv[1:]
    what = args[0] if args and args[0] in ("sfx", "music") else "all"
    filters = [a for a in args if a not in ("sfx", "music")]
    if what in ("sfx", "all"):
        gen_sfx(filters)
    if what in ("music", "all"):
        gen_music(filters)
